local ModName = "ScufflesMetalFarmCollection"
local Sn2ModSettingsDir = "./ue4ss/Mods/SN2ModSettings/"
local registrationsDir = Sn2ModSettingsDir .. "registrations/"
local thisModManifestPath = registrationsDir .. ModName .. ".lua"
local defaultOutputName = "%o"

