--#region SN2ModSettings Config Foo

do
    local manifest = [=[-- Auto-generated by ScufflesMetalFarmCollection. Do not edit; will be regenerated.
return {
    name        = "ScufflesMetalFarmCollection",
    version     = "1.0.0",
    author      = "Scuffle Kerfuffle",
    display     = "Scuffle's Metal Farm Collection",
    github      = "scufflekerfuffle/subnautica2mods/scufflesmetalfarmcollection",
    settings    = {
        { key="Enabled", title="Enable Automatic Metal Farm Collection",
            description="Master switch. When off, all metal farms will need to be collected manually.",
            type="toggle", default=true },
    },
}
]=]

    local enabledFile = io.open(Sn2ModSettingsDir .. "enabled.txt", "r")

    if not enabledFile then
        Log("SN2ModSettings not enabled. Manifest will not be written.")
        return
    end

    enabledFile:close()

    local attempts = 0
    local maxAttempts = 10

    local function tryWriteManifest()
        attempts = attempts + 1
        local sn2manifest = io.open(registrationsDir .. "SN2ModSettings.lua", "r")
        local initialized = sn2manifest ~= nil

        if sn2manifest then
            sn2manifest:close()
        end

        if initialized or attempts >= maxAttempts then
            if not initialized then
               CreateDirectory(registrationsDir)
            end
            if WriteText(thisModManifestPath, manifest) then
                Log(string.format("Manifest written successfully (attempt %d/%d).\n", attempts, maxAttempts))
            end
        else
            -- Retry in 1 second
            ExecuteWithDelay(1000, function()
                ExecuteInGameThread(tryWriteManifest)
            end)
        end
    end
    -- Start polling after 1 second (give SN2ModSettings time to begin loading)
    ExecuteWithDelay(1000, function()
        ExecuteInGameThread(tryWriteManifest)
    end)
end
